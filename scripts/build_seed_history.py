#!/usr/bin/env python3
"""Rebuild app/seed_assets/seed_history.json from git history.

Run from the repository root whenever app/seed_assets/starter.json changes (see
docs/maintainers/releasing.md). Records the fingerprint of every seeded prompt and workflow
in every committed version of starter.json, plus the working copy, and updates
the checksums of it and of starter.json in manifest.json. The seed resync uses it to tell an
unchanged earlier seed (safe to update) from one a practice has customised.

    python scripts/build_seed_history.py
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.services import seed_fingerprint  # noqa: E402

ASSETS = ROOT / 'app' / 'seed_assets'
STARTER = 'app/seed_assets/starter.json'


def versions():
    commits = subprocess.run(
        ['git', 'log', '--format=%H', '--reverse', '--', STARTER],
        cwd=ROOT, check=True, capture_output=True, text=True).stdout.split()
    for commit in commits:
        raw = subprocess.run(['git', 'show', f'{commit}:{STARTER}'],
                             cwd=ROOT, check=True, capture_output=True).stdout
        yield json.loads(raw)
    yield json.loads((ROOT / STARTER).read_text())


def main():
    history = {'system_prompts': {}, 'user_prompts': {}, 'pipelines': {}}
    for starter in versions():
        for category, items in seed_fingerprint.starter_fingerprints(starter).items():
            for name, fingerprint in items.items():
                seen = history[category].setdefault(name, [])
                if fingerprint not in seen:
                    seen.append(fingerprint)
    out = {
        '_comment': ('Fingerprints of every released version of each seeded item, oldest first. '
                     'Generated by scripts/build_seed_history.py; do not edit by hand.'),
        **{c: dict(sorted(v.items())) for c, v in history.items()},
    }
    raw = (json.dumps(out, indent=1, ensure_ascii=False) + '\n').encode()
    (ASSETS / 'seed_history.json').write_bytes(raw)
    manifest_path = ASSETS / 'manifest.json'
    manifest = json.loads(manifest_path.read_text())
    manifest['files']['seed_history.json'] = hashlib.sha256(raw).hexdigest()
    # starter.json has just changed too (that is why this runs): its checksum with it.
    manifest['files']['starter.json'] = hashlib.sha256((ASSETS / 'starter.json').read_bytes()).hexdigest()
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
    print(', '.join(f'{c}: {len(v)} names' for c, v in history.items()))


if __name__ == '__main__':
    main()
