    D1.DOCUMENTID,
    D1.STORED,
    D1.INTERNALID,
    TRIM(D1.CATEGORY)  AS Category,
    TRIM(D1.DETAIL)    AS Detail,
    CONVERT(VARCHAR(10), D1.CORRESPONDENCEDATE, 103) AS CorrespondenceDate,
    TRIM(D1.ContactName) AS ContactName,
    D2.DOCUMENTPAGEID
