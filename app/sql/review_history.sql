-- Criterion review (ADR-109): the cohort's coded past-history items (as patient_history_codes).
WITH Cohort AS (
    -- Active patients with a visit in the last 24 months.
    SELECT P.INTERNALID
    FROM PATIENTS P
    WHERE P.PATIENTSTATUS = 1
      AND EXISTS (SELECT 1 FROM VISITS V WHERE V.INTERNALID = P.INTERNALID AND V.RECORDSTATUS = 1
                  AND V.VISITDATE >= DATEADD(MONTH, -24, GETDATE()))
)
SELECT PH.INTERNALID AS patient_id, PH.ITEMCODE, TRIM(PH.ITEMTEXT) AS ITEMTEXT, PH.YEAR, PH.RECORDID, PH.STATUSCODE
FROM PASTHISTORY PH
JOIN Cohort C ON C.INTERNALID = PH.INTERNALID
WHERE PH.RECORDSTATUS = 1 AND PH.ITEMCODE > 0;
