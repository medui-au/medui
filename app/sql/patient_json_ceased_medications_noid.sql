SELECT CURRENTRX.PRODUCTID,
       UPPER(RTRIM(LEFT(CURRENTRX.DRUGNAME, 30))) AS DRUGNAME,
       CONVERT(VARCHAR(10), CURRENTRX.FIRSTDATE, 23) AS FIRSTDATE,
       CONVERT(VARCHAR(10), CURRENTRX.DELETIONDATE, 23) AS DELETIONDATE,
       RTRIM(CURRENTRX.DELETIONREASON) AS DELETIONREASON
FROM CURRENTRX
WHERE CURRENTRX.INTERNALID = ?
  AND CURRENTRX.DELETIONDATE < GETDATE()
  AND CURRENTRX.DELETIONREASON IS NOT NULL
  AND TRIM(CURRENTRX.DELETIONREASON) NOT IN ('', 'Limited Medication', 'No Longer Required', 'Completed course')
ORDER BY CURRENTRX.DELETIONDATE DESC;
