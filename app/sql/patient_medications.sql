SELECT
    CURRENTRX.PRODUCTID,
    UPPER(Left(CURRENTRX.DRUGNAME, 30)) AS DRUGNAME,
    LEFT((CASE WHEN CURRENTRX.DOSE IS NOT NULL THEN UPPER(RTRIM(CURRENTRX.DOSE)) + ' ' ELSE '' END) +  
         (CASE WHEN CURRENTRX.INSTRUCTIONS IS NOT NULL THEN UPPER(RTRIM(CURRENTRX.INSTRUCTIONS)) ELSE '' END) + 
         (CASE WHEN FREQUENCYTEXT IS NOT NULL THEN UPPER(RTRIM(FREQUENCYTEXT)) ELSE '' END), 50) AS DOSESTRING, 
    DatePart(yyyy, CURRENTRX.FIRSTDATE) AS FIRSTYEAR 
FROM CURRENTRX 
INNER JOIN FREQUENCYCODES ON CURRENTRX.FREQUENCY = FREQUENCYCODES.FREQUENCYCODE 
WHERE (CURRENTRX.INTERNALID = ?) AND (CURRENTRX.RECORDSTATUS = 1) AND (RXSTATUS = 1) 
ORDER BY FIRSTYEAR DESC;
