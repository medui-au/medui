SELECT
CASE
    WHEN MaxDate721 IS NULL AND MaxDate965 IS NULL AND MaxDate967 IS NULL THEN 'None Prior'
    WHEN MaxDate965 > DATEADD(month, -3, GETDATE()) OR MaxDate967 > DATEADD(month, -3, GETDATE()) THEN 'Neither'
    WHEN MaxDate721 > COALESCE(MaxDate965, '1900-01-01') AND MaxDate721 > COALESCE(MaxDate967, '1900-01-01') THEN '965'
    WHEN MaxDate965 <= DATEADD(month, -12, GETDATE()) THEN '965'
    WHEN MaxDate965 <= DATEADD(month, -3, GETDATE()) THEN '967'
    ELSE 'None Prior'
END AS Eligibility
FROM (
    SELECT
    MAX(CASE WHEN SERVICES.MBSITEM = '721' THEN SERVICES.SERVICEDATE END) AS MaxDate721,
    MAX(CASE WHEN SERVICES.MBSITEM IN ('392', '965') THEN SERVICES.SERVICEDATE END) AS MaxDate965,
    MAX(CASE WHEN SERVICES.MBSITEM IN ('393', '967') THEN SERVICES.SERVICEDATE END) AS MaxDate967
    FROM INVOICES
    INNER JOIN SERVICES ON INVOICES.INVOICEID = SERVICES.INVOICEID
    WHERE INVOICES.INTERNALID = ? 
      AND SERVICES.SERVICEDATE > DATEADD(year, -10, GETDATE())
      AND SERVICES.MBSITEM IN ('721', '965', '967', '392', '393')
      AND INVOICES.RECORDSTATUS <> 2
) AS Summary;