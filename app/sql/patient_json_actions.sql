SELECT CONVERT(VARCHAR(10), [ACTIONS].[DUEDATE], 120) AS DUEDATE, ACTIONS.ACTIONTEXT, 
CASE WHEN PERFORMED < Getdate() then 'true' else 'false' END AS PERFCODE
FROM ACTIONS 
INNER JOIN USERS ON ACTIONS.USERID = USERS.USERID
WHERE (ACTIONS.INTERNALID = ?) AND ACTIONS.USERId > 0  AND DATEDIFF (YY, DUEDATE, GETDATE()) <2
ORDER BY ACTIONS.DUEDATE DESC;
