SELECT
    ir.REPORTID,
    ir.REPORTHEADER,
    ir.REPORTBODY,
    ir.InternalID AS INTERNALID,
    FORMAT(ir.CollectionDate, 'dd/MM/yy') AS CollectionDate,
    irp.CONTENT,
    TRIM(irp.DOCTYPE)  AS DOCTYPE,
    COALESCE(TRIM(u.FIRSTNAME) + ' ' + TRIM(u.SURNAME), '') AS DOCTOR_NAME,
    u.USERID AS DOCTOR_USERID   -- for the preferred name (ADR-106)
FROM INCOMINGREPORTS ir
LEFT JOIN BPSDOCUMENTSINBOX.dbo.INCOMINGREPORTPAGES irp ON ir.REPORTID = irp.REPORTID
LEFT JOIN USERS u ON ir.USERID = u.USERID
WHERE ir.ReportId = ?
