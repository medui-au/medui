SELECT
    i.REPORTID,
    i.REPORTHEADER,
    i.REPORTBODY,
    i.STORED,
    i.InternalID AS INTERNALID,
    FORMAT(i.CollectionDate, 'dd/MM/yy') AS CollectionDate,
    ip.INVESTIGATIONPAGEID,
    COALESCE(TRIM(u.FIRSTNAME) + ' ' + TRIM(u.SURNAME), '') AS DOCTOR_NAME,
    u.USERID AS DOCTOR_USERID   -- for the preferred name (ADR-106)
FROM INVESTIGATIONS i
LEFT JOIN INVESTIGATIONPAGES ip ON i.REPORTID = ip.REPORTID
LEFT JOIN USERS u ON i.USERID = u.USERID
