SELECT ISNULL(CASE WHEN ALCOHOL.DAYSPERWEEK * ALCOHOL.DRINKSPERDAY > 0
            THEN CAST(ALCOHOL.DAYSPERWEEK * ALCOHOL.DRINKSPERDAY AS VARCHAR) + ' (over ' + CAST(ALCOHOL.DAYSPERWEEK AS VARCHAR) + ' days)'
            ELSE CASE WHEN ALCOHOL.ALCOHOLCODE = 1 THEN 'Non Drinker' ELSE 'No Data' END
       END, '') AS ALCOHOLPERWEEK,
       ISNULL(TRIM(CLINICAL.OTHERCOMMENT), '') AS CHARTFLAG,
       ISNULL(CASE WHEN (LOWER(SMOKINGSTATUS.SMOKINGTEXT) LIKE 'ex smoker' AND TOBACCO.PASTSTOPPED > 0)
            THEN SMOKINGSTATUS.SMOKINGTEXT + ' ('+ CAST(TOBACCO.PASTSTOPPED AS VARCHAR) + ')'
            ELSE SMOKINGSTATUS.SMOKINGTEXT
       END, '') AS SMOKING,
       ISNULL(TRIM(MARITALSTATUS.MARITALSTATUSNAME), '') AS MaritalStatus,
       CASE
           WHEN CLINICAL.RETIRED = 1 THEN 'Retired '
           ELSE ''
       END +
       ISNULL(
           (SELECT TOP (1) RTRIM([OCCUPATION])
            FROM [BPSPATIENTS].[dbo].[OCCUPATIONHISTORY]
            WHERE INTERNALID = PATIENTS.INTERNALID
            ORDER BY recordid DESC), ''
       ) AS Occupation
FROM PATIENTS
INNER JOIN CLINICAL ON PATIENTS.INTERNALID = CLINICAL.INTERNALID
-- ALCOHOL, TOBACCO and the status lookups are optional (ADR-145): about a quarter of
-- patients have no ALCOHOL or TOBACCO row, and an inner join lost their whole social history.
LEFT JOIN ALCOHOL ON PATIENTS.INTERNALID = ALCOHOL.INTERNALID
LEFT JOIN TOBACCO ON PATIENTS.INTERNALID = TOBACCO.INTERNALID
LEFT JOIN ALCOHOLSTATUS ON ALCOHOL.ALCOHOLCODE = ALCOHOLSTATUS.ALCOHOLCODE
LEFT JOIN SMOKINGSTATUS ON TOBACCO.SMOKINGCODE = SMOKINGSTATUS.SMOKINGCODE
LEFT JOIN MARITALSTATUS ON CLINICAL.MARITALSTATUS = MARITALSTATUS.MARITALSTATUSCODE
WHERE Patients.InternalID = ?;
