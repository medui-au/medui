SELECT  
    REMINDERSSENT.SENTDATE, 
    REMINDERS.REMINDERID, 
    REMINDERS.RECORDSTATUS, 
    REMINDERS.REMINDERSTATUS, 
    REMINDERS.INTERNALID, 
    REMINDERS.USERID, 
    TRIM(REMINDERS.REASONTEXT) AS REASONTEXT, 
    REMINDERS.REMINDERDUE, 
    CASE WHEN SENTDATE IS NULL THEN 'false' ELSE 'true' END AS SENT,
    -- Unified strikethrough logic: Sent OR RecordStatus != 1 OR ReminderStatus != 1
    CASE 
        WHEN (SENTDATE IS NOT NULL) OR (REMINDERS.RECORDSTATUS <> 1) OR (REMINDERS.REMINDERSTATUS <> 1) 
        THEN 'true' 
        ELSE 'false' 
    END AS IS_STRUCK
FROM REMINDERS 
LEFT OUTER JOIN REMINDERSSENT ON REMINDERS.REMINDERID = REMINDERSSENT.REMINDERID 
WHERE Reminders.InternalId = ? 
ORDER BY REMINDERDUE DESC;
