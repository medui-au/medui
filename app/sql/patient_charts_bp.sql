SELECT
    [INTERNALID],
    [OBSDATE] AS ReportDate,
    MAX(CASE WHEN DATACODE = 3 THEN TRY_CAST(DATAVALUE AS INT) END) AS Systolic,
    MAX(CASE WHEN DATACODE = 4 THEN TRY_CAST(DATAVALUE AS INT) END) AS Diastolic
FROM [BPSPATIENTS].[dbo].[OBSERVATIONS]
WHERE INTERNALID = ?
  AND RECORDSTATUS = 1
  AND DATACODE IN (3, 4)
  AND TRY_CAST(DATAVALUE AS INT) > 10
  AND TRY_CAST(DATAVALUE AS INT) < 300
GROUP BY 
    [INTERNALID], 
    [OBSDATE]
HAVING 
    MAX(CASE WHEN DATACODE = 3 THEN TRY_CAST(DATAVALUE AS INT) END) IS NOT NULL
    AND MAX(CASE WHEN DATACODE = 4 THEN TRY_CAST(DATAVALUE AS INT) END) IS NOT NULL;
