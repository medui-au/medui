SELECT CONVERT(VARCHAR(10), GivenDate, 103) AS VacDate, TRIM(IMMUNISATIONS.VACCINENAME) AS VACCINENAME, IMMUNISATIONS.SEQUENCE
FROM IMMUNISATIONS INNER JOIN USERS ON IMMUNISATIONS.USERID = USERS.USERID
WHERE (IMMUNISATIONS.INTERNALID = ?) AND (IMMUNISATIONS.RECORDSTATUS = 1)
ORDER BY Givendate Desc;
