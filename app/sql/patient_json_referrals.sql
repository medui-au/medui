WITH RankedCorrespondence AS (
    SELECT  
        CORRESPONDENCEOUT.STORED, 
        CORRESPONDENCEOUT.INTERNALID, 
        CORRESPONDENCEOUT.CORRESPONDENCEDATE, 
        CORRESPONDENCEOUT.CONTACTNAME, 
        CATEGORIES.CATEGORYNAME,
        ROW_NUMBER() OVER (
            PARTITION BY CATEGORIES.CATEGORYNAME 
            ORDER BY CORRESPONDENCEOUT.CORRESPONDENCEDATE DESC, CORRESPONDENCEOUT.STORED DESC
        ) as LatestRank
    FROM    
        CORRESPONDENCEOUT 
    INNER JOIN CONTACTS 
        ON CORRESPONDENCEOUT.CONTACTID = CONTACTS.CONTACTID 
    INNER JOIN CATEGORIES 
        ON CONTACTS.CATEGORYCODE = CATEGORIES.CATEGORYCODE
    WHERE  
        CORRESPONDENCEOUT.INTERNALID = ? 
        AND CORRESPONDENCEOUT.RECORDSTATUS = 1 
        AND DATEDIFF(yy, CORRESPONDENCEOUT.CORRESPONDENCEDATE, GETDATE()) < 5
)
SELECT 
    CONVERT(VARCHAR(10), CORRESPONDENCEDATE, 120) AS LAST_REFERRAL_DATE, 
    TRIM(CONTACTNAME) AS CONTACTNAME, 
    TRIM(CATEGORYNAME) AS CATEGORYNAME
FROM 
    RankedCorrespondence
WHERE 
    LatestRank = 1
ORDER BY 
    LAST_REFERRAL_DATE DESC;
