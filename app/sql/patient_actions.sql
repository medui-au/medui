SELECT TOP(10) ACTIONS.USERID, ACTIONS.ACTIONTEXT, ACTIONS.DUEDATE,
ACTIONS.RecordStatus, ACTIONS.ACTIONSTATUS, USERS.SURNAME, USERS.FIRSTNAME,
CASE WHEN PERFORMED < Getdate() then 'true' else 'false' END AS PERFCODE
FROM ACTIONS INNER JOIN USERS ON ACTIONS.USERID = USERS.USERID
WHERE  (ACTIONS.INTERNALID = ?) AND ACTIONS.USERId > 0
ORDER BY ACTIONS.DUEDATE DESC;
